import { useSyncExternalStore } from 'react';
import type { Dannye } from '../tipy/tipy';
import { primer } from '../dannye/primer';
const KEY = 'dom-dela-demo-v1';
const read = (): Dannye => { try { return JSON.parse(localStorage.getItem(KEY) || 'null') || primer(); } catch { return primer(); } };
let demo = read(), current = demo;
const listeners = new Set<() => void>();
type Status = { cloud: boolean; loading: boolean; error: string };
let status: Status = { cloud: false, loading: false, error: '' };
const emit = () => listeners.forEach(fn => fn());
export const getData = () => current;
export const getStatus = () => status;
export const setStatus = (change: Partial<Status>) => { status = { ...status, ...change }; emit(); };
export const setCloudData = (data: Dannye) => { current = data; setStatus({ cloud: true, loading: false, error: '' }); };
export const leaveCloud = () => { current = { ...demo, currentUserId: undefined }; setStatus({ cloud: false, loading: false, error: '' }); };
export const setData = (change: (data: Dannye) => Dannye) => {
  if (status.cloud) throw new Error('Облачные изменения должны выполняться через Supabase.');
  demo = change(demo); current = demo; localStorage.setItem(KEY, JSON.stringify(demo)); emit();
};
export const useData = () => useSyncExternalStore(fn => { listeners.add(fn); return () => listeners.delete(fn); }, getData);
export const useCloudStatus = () => useSyncExternalStore(fn => { listeners.add(fn); return () => listeners.delete(fn); }, getStatus);
export const resetDemo = () => { demo = primer(); if (!status.cloud) current = demo; localStorage.setItem(KEY, JSON.stringify(demo)); emit(); };
